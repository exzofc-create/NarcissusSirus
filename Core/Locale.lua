local currentSpec = nil

NS.LSpec = setmetatable({}, {
    __index = function(_, key)
        if currentSpec then
            local text = currentSpec[key]
            if text then return text end
        end
        return key
    end,
})

NS.LOCALE_OPTIONS = {
    { key = "auto",  label = "Авто / Auto" },
    { key = "ruRU",  label = "Русский" },
    { key = "enUS",  label = "English" },
}

function NS.ResolveLocale(key)
    if not key or key == "auto" then
        local client = GetLocale and GetLocale() or "ruRU"
        return client == "ruRU" and "ruRU" or "enUS"
    end
    return key == "ruRU" and "ruRU" or "enUS"
end

function NS.ApplyLocale(key)
    local resolved = NS.ResolveLocale(key)
    NS.localeKey = resolved
    local english = resolved ~= "ruRU"
    current = english and translations.enUS or nil
    currentSpec = english and specTranslations.enUS or nil
end

